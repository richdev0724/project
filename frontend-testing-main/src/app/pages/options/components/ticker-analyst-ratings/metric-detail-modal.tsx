import { Dialog, DialogContent } from '@/components/ui/dialog'
import { TrendingUp, Calculator, BarChart3, PieChart, Info } from 'lucide-react'

interface MetricDetailModalProps {
  isOpen: boolean
  onClose: () => void
  metricType: 'DCF' | 'PE' | 'ROE' | 'ROA' | 'DE' | 'PB'
  value: string
  score: number
}

const MetricDetailModal = ({
  isOpen,
  onClose,
  metricType,
  value,
  score,
}: MetricDetailModalProps) => {
  const getMetricDetails = () => {
    switch (metricType) {
      case 'DCF':
        return {
          fullName: 'Discounted Cash Flow Analysis',
          shortDesc: 'Intrinsic value based on projected future cash flows',
          formula: 'DCF = Σ [CFₜ / (1+r)ᵗ] + Terminal Value / (1+r)ⁿ',
          components: [
            {
              name: 'Free Cash Flow (FCF)',
              description:
                'Cash generated by operations minus capital expenditures',
              formula: 'FCF = Operating Cash Flow - CapEx',
              icon: TrendingUp,
            },
            {
              name: 'Discount Rate (WACC)',
              description:
                'Weighted Average Cost of Capital - required rate of return',
              formula: 'WACC = (E/V × Re) + (D/V × Rd × (1-Tc))',
              icon: Calculator,
            },
            {
              name: 'Terminal Value',
              description:
                'Estimated value of all future cash flows beyond forecast period',
              formula: 'TV = FCF × (1+g) / (WACC - g)',
              icon: BarChart3,
            },
            {
              name: 'Present Value',
              description: 'Sum of all discounted future cash flows',
              formula: 'PV = Future Value / (1 + r)ⁿ',
              icon: PieChart,
            },
          ],
          interpretation: [
            {
              condition: 'DCF > Stock Price',
              meaning: 'Potentially undervalued',
              color: 'text-[#45CA89]',
            },
            {
              condition: 'DCF = Stock Price',
              meaning: 'Fairly valued',
              color: 'text-[#FFA500]',
            },
            {
              condition: 'DCF < Stock Price',
              meaning: 'Potentially overvalued',
              color: 'text-[#FF6B6B]',
            },
          ],
          calculation: `
1. Project Free Cash Flows for 5-10 years
2. Calculate WACC based on company's capital structure
3. Discount each year's FCF to present value
4. Calculate Terminal Value using perpetuity growth
5. Sum all PV + Terminal Value = DCF Value
6. Compare DCF to current stock price for valuation
          `,
          scoreLogic:
            'Higher score means DCF significantly exceeds current price (undervalued)',
        }
      case 'PE':
        return {
          fullName: 'Price-to-Earnings Ratio',
          shortDesc: 'How much investors pay per dollar of earnings',
          formula: 'P/E Ratio = Stock Price / Earnings Per Share',
          components: [
            {
              name: 'Stock Price',
              description: 'Current market price per share',
              formula: 'Market Price',
              icon: TrendingUp,
            },
            {
              name: 'Earnings Per Share (EPS)',
              description: 'Company profit allocated to each outstanding share',
              formula: 'EPS = Net Income / Shares Outstanding',
              icon: Calculator,
            },
            {
              name: 'Trailing P/E',
              description: 'Based on last 12 months of actual earnings',
              formula: 'TTM P/E = Current Price / TTM EPS',
              icon: BarChart3,
            },
            {
              name: 'Forward P/E',
              description: 'Based on next 12 months estimated earnings',
              formula: 'Forward P/E = Current Price / Estimated EPS',
              icon: PieChart,
            },
          ],
          interpretation: [
            {
              condition: 'Low P/E (< Industry Avg)',
              meaning: 'Potentially undervalued or declining growth',
              color: 'text-[#45CA89]',
            },
            {
              condition: 'Average P/E',
              meaning: 'Fairly valued relative to peers',
              color: 'text-[#FFA500]',
            },
            {
              condition: 'High P/E (> Industry Avg)',
              meaning: 'Growth expectations or overvalued',
              color: 'text-[#FF6B6B]',
            },
          ],
          calculation: `
1. Get current stock price from market
2. Calculate EPS from financial statements:
   - Net Income / Total Shares Outstanding
3. Divide Stock Price by EPS
4. Compare to:
   - Industry average P/E
   - Historical company P/E
   - Market average (S&P 500 ~20)
          `,
          scoreLogic: 'Lower relative P/E = higher score (better value)',
        }
      case 'ROE':
        return {
          fullName: 'Return on Equity',
          shortDesc: 'Profit generated from shareholder investments',
          formula: "ROE = (Net Income / Shareholders' Equity) × 100%",
          components: [
            {
              name: 'Net Income',
              description: 'Company profit after all expenses and taxes',
              formula: 'Revenue - All Expenses - Taxes',
              icon: TrendingUp,
            },
            {
              name: "Shareholders' Equity",
              description: 'Assets minus liabilities (book value)',
              formula: 'Total Assets - Total Liabilities',
              icon: Calculator,
            },
            {
              name: 'DuPont Analysis',
              description:
                'Breaks ROE into profitability, efficiency, and leverage',
              formula:
                'ROE = Profit Margin × Asset Turnover × Equity Multiplier',
              icon: BarChart3,
            },
            {
              name: 'Benchmark',
              description: 'Compare to industry and historical performance',
              formula: '>15% is generally strong',
              icon: PieChart,
            },
          ],
          interpretation: [
            {
              condition: 'ROE > 20%',
              meaning: 'Excellent efficiency and profitability',
              color: 'text-[#45CA89]',
            },
            {
              condition: 'ROE 15-20%',
              meaning: 'Good, healthy returns',
              color: 'text-[#45CA89]',
            },
            {
              condition: 'ROE 10-15%',
              meaning: 'Average performance',
              color: 'text-[#FFA500]',
            },
            {
              condition: 'ROE < 10%',
              meaning: 'Below average, potential issues',
              color: 'text-[#FF6B6B]',
            },
          ],
          calculation: `
1. Find Net Income from Income Statement
2. Find Shareholders' Equity from Balance Sheet
3. Divide Net Income by Shareholders' Equity
4. Multiply by 100 for percentage
5. Compare to:
   - Industry average (varies greatly)
   - Historical company ROE
   - 15% benchmark (generally strong)
          `,
          scoreLogic: 'Higher ROE = higher score (more efficient)',
        }
      case 'ROA':
        return {
          fullName: 'Return on Assets',
          shortDesc: 'Profit generated from total assets',
          formula: 'ROA = (Net Income / Total Assets) × 100%',
          components: [
            {
              name: 'Net Income',
              description: 'Company profit after all expenses',
              formula: 'Revenue - All Expenses - Taxes',
              icon: TrendingUp,
            },
            {
              name: 'Total Assets',
              description: 'Everything the company owns',
              formula: 'Current Assets + Fixed Assets',
              icon: Calculator,
            },
            {
              name: 'Asset Turnover',
              description: 'How efficiently assets generate revenue',
              formula: 'Revenue / Total Assets',
              icon: BarChart3,
            },
            {
              name: 'Benchmark',
              description: 'Varies significantly by industry',
              formula: '>5% is generally good',
              icon: PieChart,
            },
          ],
          interpretation: [
            {
              condition: 'ROA > 10%',
              meaning: 'Excellent asset utilization',
              color: 'text-[#45CA89]',
            },
            {
              condition: 'ROA 5-10%',
              meaning: 'Good efficiency',
              color: 'text-[#45CA89]',
            },
            {
              condition: 'ROA 2-5%',
              meaning: 'Average for capital-intensive industries',
              color: 'text-[#FFA500]',
            },
            {
              condition: 'ROA < 2%',
              meaning: 'Poor asset utilization',
              color: 'text-[#FF6B6B]',
            },
          ],
          calculation: `
1. Find Net Income from Income Statement
2. Find Total Assets from Balance Sheet
3. Divide Net Income by Total Assets
4. Multiply by 100 for percentage
5. Compare to:
   - Industry peers (crucial - varies widely)
   - Company history
   - 5% general benchmark
          `,
          scoreLogic: 'Higher ROA = higher score (better asset efficiency)',
        }
      case 'DE':
        return {
          fullName: 'Debt-to-Equity Ratio',
          shortDesc: 'Financial leverage and debt burden',
          formula: "D/E Ratio = Total Liabilities / Shareholders' Equity",
          components: [
            {
              name: 'Total Debt',
              description: 'Short-term + long-term debt obligations',
              formula: 'Current Liabilities + Long-term Debt',
              icon: TrendingUp,
            },
            {
              name: "Shareholders' Equity",
              description: "Owner's stake in the company",
              formula: 'Total Assets - Total Liabilities',
              icon: Calculator,
            },
            {
              name: 'Leverage Impact',
              description: 'Higher leverage amplifies returns and risks',
              formula: 'Financial Risk vs Growth Potential',
              icon: BarChart3,
            },
            {
              name: 'Industry Context',
              description: 'Acceptable levels vary by sector',
              formula: 'Compare to industry norms',
              icon: PieChart,
            },
          ],
          interpretation: [
            {
              condition: 'D/E < 0.5',
              meaning: 'Conservative, low financial risk',
              color: 'text-[#45CA89]',
            },
            {
              condition: 'D/E 0.5-1.0',
              meaning: 'Moderate leverage, balanced',
              color: 'text-[#45CA89]',
            },
            {
              condition: 'D/E 1.0-2.0',
              meaning: 'Higher leverage, acceptable for some industries',
              color: 'text-[#FFA500]',
            },
            {
              condition: 'D/E > 2.0',
              meaning: 'High financial risk',
              color: 'text-[#FF6B6B]',
            },
          ],
          calculation: `
1. Find Total Liabilities from Balance Sheet
2. Find Shareholders' Equity from Balance Sheet
3. Divide Total Liabilities by Shareholders' Equity
4. Compare to:
   - Industry average (critical context)
   - Company history
   - 1.0 benchmark (equal debt & equity)
   - Higher in capital-intensive industries
          `,
          scoreLogic:
            'Lower D/E = higher score (less risky), but context matters',
        }
      case 'PB':
        return {
          fullName: 'Price-to-Book Ratio',
          shortDesc: 'Market value relative to book value',
          formula: 'P/B Ratio = Market Price / Book Value Per Share',
          components: [
            {
              name: 'Market Price',
              description: 'Current stock price',
              formula: 'Current Trading Price',
              icon: TrendingUp,
            },
            {
              name: 'Book Value Per Share',
              description: 'Net asset value per share',
              formula: "Shareholders' Equity / Shares Outstanding",
              icon: Calculator,
            },
            {
              name: 'Tangible Book Value',
              description: 'Excludes intangible assets like goodwill',
              formula: 'Book Value - Intangible Assets',
              icon: BarChart3,
            },
            {
              name: 'Valuation Signal',
              description: 'Indicates over or undervaluation',
              formula: 'Compare to 1.0 and industry',
              icon: PieChart,
            },
          ],
          interpretation: [
            {
              condition: 'P/B < 1.0',
              meaning: 'Trading below book value, potential undervaluation',
              color: 'text-[#45CA89]',
            },
            {
              condition: 'P/B 1.0-3.0',
              meaning: 'Reasonable valuation for most stocks',
              color: 'text-[#45CA89]',
            },
            {
              condition: 'P/B 3.0-5.0',
              meaning: 'Premium valuation, growth expected',
              color: 'text-[#FFA500]',
            },
            {
              condition: 'P/B > 5.0',
              meaning: 'Very high premium, potential overvaluation',
              color: 'text-[#FF6B6B]',
            },
          ],
          calculation: `
1. Get current stock price from market
2. Calculate Book Value Per Share:
   - Shareholders' Equity / Total Shares
3. Divide Market Price by Book Value Per Share
4. Compare to:
   - 1.0 (trading at book value)
   - Industry average
   - Historical company P/B
   - Growth vs value stocks context
          `,
          scoreLogic:
            'Lower P/B = higher score (better value), especially < 3.0',
        }
      default:
        return {
          fullName: '',
          shortDesc: '',
          formula: '',
          components: [],
          interpretation: [],
          calculation: '',
          scoreLogic: '',
        }
    }
  }

  const details = getMetricDetails()

  const getScoreColor = (score: number) => {
    if (score >= 4) return 'from-[#45CA89] to-[#00FF88]'
    if (score >= 3) return 'from-[#FFA500] to-[#FFD700]'
    return 'from-[#FF6B6B] to-[#FFA500]'
  }

  return (
    <Dialog open={isOpen} onOpenChange={onClose}>
      <DialogContent
        className='flex max-h-[85vh] max-w-4xl flex-col overflow-y-auto rounded-xl border border-white/10 bg-[#1F2026]/40 p-8 backdrop-blur-xl !duration-500 data-[state=closed]:!scale-100 data-[state=open]:!scale-100 sm:max-w-4xl'
        style={{
          background:
            'linear-gradient(135deg, rgba(31, 32, 38, 0.4) 0%, rgba(31, 32, 38, 0.2) 100%)',
          boxShadow:
            '0 20px 50px -12px rgba(0, 0, 0, 0.5), 0 8px 32px 0 rgba(0, 0, 0, 0.37), inset 0 1px 0 0 rgba(255, 255, 255, 0.05)',
        }}
      >
        <div className='text-[#F5F7F7]/80'>
          <div className='flex items-start justify-between'>
            <div className='flex-1'>
              <h1 className='text-xl font-bold text-[#F5F7F7]'>
                {details.fullName}
              </h1>
              <p className='mt-1.5 text-xs text-[#F5F7F7]/70'>
                {details.shortDesc}
              </p>
            </div>
            <div className='ml-4 flex items-center gap-3'>
              <div
                className={`flex h-12 w-12 items-center justify-center rounded-lg bg-gradient-to-br ${getScoreColor(score)} shadow-lg`}
              >
                <span className='text-xl font-black text-white'>
                  {score.toFixed(1)}
                </span>
              </div>
            </div>
          </div>

          <div className='my-4 h-px w-full bg-sky-500/50'></div>

          <div className='space-y-4 pt-2'>
            {/* Formula Section */}
            <div className='rounded-lg border border-white/10 bg-gradient-to-br from-gray-800/40 to-gray-900/30 p-3'>
              <div className='mb-2 flex items-center gap-2'>
                <Calculator className='h-4 w-4 text-[#45CA89]' />
                <h3 className='text-base font-bold text-[#F5F7F7]'>Formula</h3>
              </div>
              <div className='rounded-lg bg-gray-900/60 p-3'>
                <code className='font-mono text-sm text-[#45CA89]'>
                  {details.formula}
                </code>
              </div>
            </div>

            {/* Components Breakdown */}
            <div className='rounded-lg border border-white/10 bg-gradient-to-br from-gray-800/40 to-gray-900/30 p-3'>
              <div className='mb-2 flex items-center gap-2'>
                <PieChart className='h-4 w-4 text-[#45CA89]' />
                <h3 className='text-base font-bold text-[#F5F7F7]'>
                  Key Components
                </h3>
              </div>
              <div className='grid gap-2 md:grid-cols-2'>
                {details.components.map((component, index) => {
                  const Icon = component.icon
                  return (
                    <div
                      key={index}
                      className='rounded-lg border border-white/10 bg-gray-900/40 p-3 transition-all duration-200 hover:border-gray-600 hover:bg-gray-800/60'
                    >
                      <div className='mb-1.5 flex items-center gap-1.5'>
                        <div className='rounded bg-[#45CA89]/20 p-1.5'>
                          <Icon className='h-3.5 w-3.5 text-[#45CA89]' />
                        </div>
                        <h4 className='text-sm font-semibold text-[#F5F7F7]'>
                          {component.name}
                        </h4>
                      </div>
                      <p className='text-xs text-[#F5F7F7]/70'>
                        {component.description}
                      </p>
                      <div className='mt-2 rounded bg-gray-900/60 p-1.5'>
                        <code className='text-[10px] text-[#FFA500]'>
                          {component.formula}
                        </code>
                      </div>
                    </div>
                  )
                })}
              </div>
            </div>

            {/* Calculation Steps */}
            <div className='rounded-lg border border-white/10 bg-gradient-to-br from-gray-800/40 to-gray-900/30 p-3'>
              <div className='mb-2 flex items-center gap-2'>
                <BarChart3 className='h-4 w-4 text-[#45CA89]' />
                <h3 className='text-base font-bold text-[#F5F7F7]'>
                  How It's Calculated
                </h3>
              </div>
              <pre className='whitespace-pre-wrap rounded-lg bg-gray-900/60 p-3 text-xs text-[#F5F7F7]/80'>
                {details.calculation}
              </pre>
            </div>

            {/* Interpretation Guide */}
            <div className='rounded-lg border border-white/10 bg-gradient-to-br from-gray-800/40 to-gray-900/30 p-3'>
              <div className='mb-2 flex items-center gap-2'>
                <Info className='h-4 w-4 text-[#45CA89]' />
                <h3 className='text-base font-bold text-[#F5F7F7]'>
                  Interpretation Guide
                </h3>
              </div>
              <div className='space-y-2'>
                {details.interpretation.map((item, index) => (
                  <div
                    key={index}
                    className='flex items-start gap-2 rounded-lg border border-white/10 bg-gray-900/40 p-2'
                  >
                    <div className='mt-0.5 h-1.5 w-1.5 rounded-full bg-gray-600' />
                    <div className='flex-1'>
                      <p className='text-sm font-semibold text-[#F5F7F7]'>
                        {item.condition}
                      </p>
                      <p className={`text-xs ${item.color}`}>{item.meaning}</p>
                    </div>
                  </div>
                ))}
              </div>
            </div>

            {/* Current Score Logic */}
            <div className='rounded-lg border border-[#45CA89]/30 bg-gradient-to-br from-[#45CA89]/10 to-transparent p-3'>
              <div className='mb-2 flex items-center gap-2'>
                <TrendingUp className='h-4 w-4 text-[#45CA89]' />
                <h3 className='text-base font-bold text-[#F5F7F7]'>
                  Current Score: {value}
                </h3>
              </div>
              <p className='text-xs text-[#F5F7F7]/80'>{details.scoreLogic}</p>
              <div className='mt-2 flex items-center gap-2'>
                <div className='h-1.5 flex-1 rounded-full bg-gray-700'>
                  <div
                    className={`h-1.5 rounded-full bg-gradient-to-r ${getScoreColor(score)} transition-all duration-500`}
                    style={{ width: `${(score / 5) * 100}%` }}
                  />
                </div>
                <span className='text-xs font-bold text-[#F5F7F7]'>
                  {score}/5
                </span>
              </div>
            </div>
          </div>
        </div>
      </DialogContent>
    </Dialog>
  )
}

export default MetricDetailModal
